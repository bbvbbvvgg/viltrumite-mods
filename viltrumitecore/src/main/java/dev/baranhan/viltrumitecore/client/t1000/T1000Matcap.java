package dev.baranhan.viltrumitecore.client.t1000;

import com.mojang.blaze3d.platform.NativeImage;
import net.minecraft.client.Minecraft;
import net.minecraft.client.renderer.texture.DynamicTexture;
import net.minecraft.resources.ResourceLocation;

/**
 * The chrome of the liquid metal: a sphere map (matcap) painted once at runtime from a procedural city
 * environment — pale overcast sky, a bright horizon with building silhouettes and lit windows, wet asphalt below,
 * a soft key light and a cool fill. The body and the droplets look it up with the perspective-corrected
 * reflection vector ({@link #uv}), so reflections slide over the metal as it moves. No binary asset: the texture
 * is generated by {@link #paint} (pure, covered by {@code T1000ShapesTest}).
 */
public final class T1000Matcap {
   public static final ResourceLocation TEXTURE = new ResourceLocation("viltrumitecore", "t1000/matcap");
   public static final int SIZE = 256;
   private static boolean registered;

   private T1000Matcap() {
   }

   /** The texture id; registers the dynamic texture on first use (render thread). */
   public static ResourceLocation texture() {
      if (!registered) {
         registered = true;
         NativeImage img = new NativeImage(SIZE, SIZE, false);
         for (int y = 0; y < SIZE; y++) {
            for (int x = 0; x < SIZE; x++) {
               int argb = paint(x, y, SIZE);
               // NativeImage stores ABGR
               int a = argb >>> 24;
               int r = argb >> 16 & 255;
               int g = argb >> 8 & 255;
               int b = argb & 255;
               img.setPixelRGBA(x, y, a << 24 | b << 16 | g << 8 | r);
            }
         }
         DynamicTexture tex = new DynamicTexture(img);
         tex.setFilter(true, false);
         Minecraft.getInstance().getTextureManager().register(TEXTURE, tex);
      }
      return TEXTURE;
   }

   /**
    * Matcap coordinates from a view-space position (camera at the origin, looking down -z) and a view-space unit
    * normal. out[0] = u, out[1] = v (v down).
    */
   public static void uv(float px, float py, float pz, float nx, float ny, float nz, float[] out) {
      float len = (float)Math.sqrt(px * px + py * py + pz * pz);
      float vx = px / Math.max(1.0E-5F, len);
      float vy = py / Math.max(1.0E-5F, len);
      float vz = pz / Math.max(1.0E-5F, len);
      float d = vx * nx + vy * ny + vz * nz;
      float rx = vx - 2.0F * d * nx;
      float ry = vy - 2.0F * d * ny;
      float rz = vz - 2.0F * d * nz;
      float m = 2.0F * (float)Math.sqrt(rx * rx + ry * ry + (rz + 1.0F) * (rz + 1.0F));
      if (m < 1.0E-4F) {
         out[0] = 0.5F;
         out[1] = 0.02F;
         return;
      }
      out[0] = 0.5F + rx / m * 0.985F;
      out[1] = 0.5F - ry / m * 0.985F;
   }

   /** ARGB of matcap texel (x, y) of a size×size map. Pure. */
   public static int paint(int x, int y, int size) {
      float sx = (x + 0.5F) / size * 2.0F - 1.0F;
      float sy = 1.0F - (y + 0.5F) / size * 2.0F;
      float rr = sx * sx + sy * sy;
      if (rr > 1.0F) {
         // outside the sphere: the colour of grazing reflections (sky behind), used by the filter at the rim
         float s = 1.0F / (float)Math.sqrt(rr);
         sx *= s;
         sy *= s;
         rr = 1.0F;
      }
      float nz = (float)Math.sqrt(Math.max(0.0F, 1.0F - rr));
      // reflection of the view ray (0, 0, -1) about the sphere normal
      float rx = 2.0F * nz * sx;
      float ry = 2.0F * nz * sy;
      float rz = 2.0F * nz * nz - 1.0F;
      float[] c = env(rx, ry, rz);
      int r = toByte(c[0]);
      int g = toByte(c[1]);
      int b = toByte(c[2]);
      return 0xFF000000 | r << 16 | g << 8 | b;
   }

   private static int toByte(float v) {
      // linear to sRGB-ish
      float s = (float)Math.pow(Math.max(0.0F, Math.min(1.0F, v)), 1.0 / 2.2);
      return Math.round(s * 255.0F);
   }

   private static float hash(int i) {
      int h = i * 0x27D4EB2D;
      h ^= h >>> 15;
      h *= 0x165667B1;
      h ^= h >>> 13;
      return (h & 0xFFFF) / 65535.0F;
   }

   /** Linear RGB of the environment seen along view-space direction r (y up, -z into the screen). */
   static float[] env(float rx, float ry, float rz) {
      float len = (float)Math.sqrt(rx * rx + ry * ry + rz * rz);
      rx /= len;
      ry /= len;
      rz /= len;
      float az = (float)Math.atan2(rx, -rz);
      float r;
      float g;
      float b;
      if (ry >= 0.0F) {
         float e = (float)Math.pow(ry, 0.55);
         r = lerp(e, 0.62F, 0.30F);
         g = lerp(e, 0.66F, 0.36F);
         b = lerp(e, 0.72F, 0.48F);
         // the skyline: blocks of buildings of hashed height, a few lit windows
         int col = (int)Math.floor((az + Math.PI) / (Math.PI * 2.0) * 46.0);
         float height = 0.05F + 0.22F * hash(col) * hash(col * 7 + 3);
         if (ry < height) {
            float shade = 0.16F + 0.12F * hash(col * 13 + 1);
            float win = 0.0F;
            int wy = (int)(ry * 140.0F);
            int wx = (int)((az + Math.PI) * 60.0F);
            if (hash(wx * 31 + wy * 17) > 0.86F) {
               win = 0.35F;
            }
            r = shade + win * 0.9F;
            g = shade + win * 0.85F;
            b = shade * 1.12F + win * 0.6F;
         }
         // overcast glow just above the roofs
         float glow = (float)Math.exp(-(ry - 0.25F) * (ry - 0.25F) / 0.02F) * 0.18F;
         r += glow;
         g += glow;
         b += glow * 1.05F;
      } else {
         float e = (float)Math.pow(-ry, 0.5);
         r = lerp(e, 0.26F, 0.07F);
         g = lerp(e, 0.27F, 0.075F);
         b = lerp(e, 0.30F, 0.085F);
         // a wet bright band on the asphalt near the horizon
         float band = (float)Math.exp(-(ry + 0.06F) * (ry + 0.06F) / 0.003F) * 0.32F;
         r += band;
         g += band;
         b += band * 1.05F;
      }
      // key light (softbox, upper left behind the camera) and a cool fill from the right
      float key = Math.max(0.0F, dot(rx, ry, rz, -0.42F, 0.62F, 0.66F));
      float k = (float)Math.pow(key, 70.0) * 2.4F + (float)Math.pow(key, 9.0) * 0.32F;
      float fill = Math.max(0.0F, dot(rx, ry, rz, 0.72F, 0.18F, 0.67F));
      float f = (float)Math.pow(fill, 40.0) * 0.9F + (float)Math.pow(fill, 6.0) * 0.12F;
      r += k + f * 0.75F;
      g += k + f * 0.85F;
      b += k * 1.02F + f * 1.05F;
      // the viewer's own (dark) reflection straight back at the camera
      if (rz > 0.75F) {
         float dark = smooth01((rz - 0.75F) / 0.25F) * 0.35F;
         r *= 1.0F - dark;
         g *= 1.0F - dark;
         b *= 1.0F - dark;
      }
      return new float[]{r * 0.96F, g * 0.99F, b * 1.04F};
   }

   private static float dot(float ax, float ay, float az, float bx, float by, float bz) {
      float l = (float)Math.sqrt(bx * bx + by * by + bz * bz);
      return (ax * bx + ay * by + az * bz) / l;
   }

   private static float lerp(float t, float a, float b) {
      return a + (b - a) * t;
   }

   private static float smooth01(float t) {
      t = Math.max(0.0F, Math.min(1.0F, t));
      return t * t * (3.0F - 2.0F * t);
   }
}
