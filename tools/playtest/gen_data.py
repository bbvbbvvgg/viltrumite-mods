#!/usr/bin/env python3
"""Generate tools/playtest/data/*.json from the mod sources.

  python3 tools/playtest/gen_data.py          # rewrite data/heroes.json and data/events.json
  python3 tools/playtest/gen_data.py --check  # exit 1 if the committed files are stale

Run it after adding a hero (HeroId) or a world event (WorldEvents). Scenarios read the
files with "foreach": "@../data/heroes.json:heroes". Stdlib only.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent.parent
SRC = PROJECT / "viltrumitecore/src/main/java/dev/baranhan/viltrumitecore"
DATA = HERE / "data"


def heroes() -> list[dict]:
    text = (SRC / "hero/HeroId.java").read_text(encoding="utf-8")
    out = []
    for m in re.finditer(r'^\s+([A-Z][A-Z0-9_]*)\("([a-z0-9_]+)"\)\s*[,;]', text, re.M):
        out.append({"id": m.group(2), "enum": m.group(1), "resolves_to": m.group(2)})
    # HeroId.fromKey() maps legacy keys to another hero, e.g. "viltrumite" -> HOMELANDER.
    by_enum = {h["enum"]: h for h in out}
    for m in re.finditer(r'if \(([A-Z_]+)\.key\.equals\(key\)\)\s*\{\s*return ([A-Z_]+);', text):
        src, dst = by_enum.get(m.group(1)), by_enum.get(m.group(2))
        if src and dst:
            src["resolves_to"] = dst["id"]
            src["legacy_alias"] = True
    return out


def events() -> list[dict]:
    text = (SRC / "worldevent/WorldEvents.java").read_text(encoding="utf-8")
    rx = re.compile(r'new WorldEventType\(\s*"([a-z0-9_]+)",\s*ChatFormatting\.\w+,\s*"[^"]*",\s*"[^"]*",'
                    r'\s*"[^"]*",\s*(\d+)')
    return [{"id": m.group(1), "warmup_ticks": int(m.group(2))} for m in rx.finditer(text)]


def render() -> dict[str, str]:
    h, e = heroes(), events()
    if not h or not e:
        raise SystemExit(f"gen_data: parse failed (heroes={len(h)}, events={len(e)})")
    note = "generated by tools/playtest/gen_data.py - do not edit by hand"
    return {
        "heroes.json": json.dumps({"_note": note, "heroes": h}, indent=2, ensure_ascii=False) + "\n",
        "events.json": json.dumps({"_note": note, "events": e}, indent=2, ensure_ascii=False) + "\n",
    }


def main() -> int:
    files = render()
    if "--check" in sys.argv:
        stale = [n for n, body in files.items()
                 if not (DATA / n).exists() or (DATA / n).read_text(encoding="utf-8") != body]
        if stale:
            print("stale:", ", ".join(stale), "- run tools/playtest/gen_data.py")
            return 1
        print("data up to date")
        return 0
    DATA.mkdir(parents=True, exist_ok=True)
    for n, body in files.items():
        (DATA / n).write_text(body, encoding="utf-8")
        print("wrote", (DATA / n).relative_to(PROJECT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
